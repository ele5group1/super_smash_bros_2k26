"""Pre-battle feature contract and scoring for a locally trained lesson model."""
from hashlib import sha256
import json
import os
from pathlib import Path

from app.engine.models import TYPE_CHART

MODEL_DIR = Path(os.environ.get("BATTLE_MODEL_DIR", Path(__file__).resolve().parents[2] / "models"))
FEATURE_VERSION = 1
_CACHE = {}


def scenario_signature(scenario, roster):
    return sha256(json.dumps({"scenario": scenario.model_dump(mode="json"),
                             "roster": [c.model_dump(mode="json") for c in sorted(roster, key=lambda c:c.id)]},
                            sort_keys=True).encode()).hexdigest()


def prebattle_features(scenario, team, enemies, spend=0, personality="opportunistic"):
    """No event log, outcome, final HP, survivors, or duration may enter this function."""
    values = {"scenario": scenario.id, "objective": scenario.objective.type, "personality": personality,
              "team_size": len(team), "enemy_count": len(enemies), "potion_spend": spend,
              "starting_coins": scenario.starting_coins, "remaining_budget": scenario.starting_coins-spend,
              "tick_limit": scenario.ticks, "required_survivors": scenario.objective.min_survivors,
              "hazard_damage": sum(float(h.params.get("damage",25)) for h in scenario.hazard_schedule),
              "team_hp": sum(c.hp for c in team), "enemy_hp": sum(c.hp for c in enemies),
              "team_attack": sum(c.attack for c in team), "enemy_attack": sum(c.attack for c in enemies),
              "team_speed": sum(c.speed for c in team), "lanes": scenario.lanes}
    for i in range(4):
        values[f"slot_{i}"] = team[i].id if i < len(team) else "empty"
    for kind in ("fire","water","grass","electric","stone"):
        values[f"type_{kind}"] = sum(c.type.value == kind for c in team)
    values["type_matchup"] = sum(TYPE_CHART[c.type.value][e.type.value] for c in team for e in enemies)/max(1,len(team)*len(enemies))
    return values


def model_report():
    try:
        return json.loads((MODEL_DIR / "report.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"status": "not_trained", "message": "Run train_lesson_models.py to fit and evaluate the model."}


def score_prebattle(scenario, team, enemies, spend=0, personality="opportunistic", roster=None):
    report = model_report()
    if report.get("status") != "trained":
        return {"available": False, "reason": report.get("message", "Model unavailable")}
    roster = roster or team+enemies
    domain = report.get("training_domain", {})
    if (len(team) not in domain.get("team_size", []) or spend not in domain.get("potion_spend", [])
            or personality not in domain.get("personality", [])):
        return {"available": False, "reason": "Squad size, spending, or AI setting is outside the trained domain; use simulation."}
    allowed_ids = set(report.get("roster_ids", []))
    if any(c.id not in report.get("player_ids",[]) for c in team) or any(c.id not in allowed_ids for c in team+enemies) or report.get("feature_version") != FEATURE_VERSION:
        return {"available": False, "reason": "Squad or feature schema is outside the trained scope."}
    if scenario_signature(scenario, roster) not in report.get("scenario_signatures", []):
        return {"available": False, "reason": "Scenario or roster differs from the validated training scope; use simulation."}
    import joblib
    import sklearn
    if sklearn.__version__ != report.get("sklearn_version"):
        return {"available": False, "reason": "Retrain the model with the installed scikit-learn version."}
    path = MODEL_DIR / report["model_file"]
    # Only artifacts generated by our local training command are loaded; never uploaded pickle files.
    cache_key = (str(path), report["model_sha256"])
    try:
        if cache_key not in _CACHE:
            if sha256(path.read_bytes()).hexdigest() != report["model_sha256"]:
                return {"available": False, "reason": "Model checksum mismatch; retrain."}
            _CACHE.clear(); _CACHE[cache_key] = joblib.load(path)
        model = _CACHE[cache_key]
        features = prebattle_features(scenario, team, enemies, spend, personality)
        probability = float(model.predict_proba([features])[0,1])
        return {"available": True, "win_rate": probability, "win_rate_percent": round(probability*100,1),
                "model": report["selected_model"], "model_version": report["dataset_sha256"][:12],
                "training_source": report["data_source"],
                "note": "Learned from simulated battles; validation on actual visitors is still needed. Predictive importance is not causal effect."}
    except (OSError, ValueError, KeyError) as error:
        return {"available": False, "reason": f"Model artifact unavailable: {type(error).__name__}"}
